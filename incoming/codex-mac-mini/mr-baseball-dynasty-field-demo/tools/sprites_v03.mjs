for (const [name, rows] of Object.entries(NEW)) {
  const w = rows[0].length;
  for (let i = 0; i < rows.length; i++) {
    if (rows[i].length !== w) { console.log('BAD LEN', name, 'row', i, rows[i].length, 'want', w); ok = false; }
    if (/[^.OCcSsJjTtPpGgNnWBUK]/.test(rows[i])) { console.log('BAD CHAR', name, 'row', i, rows[i]); ok = false; }
  }
  console.log(name.padEnd(16), w + 'x' + rows.length);
}
console.log(ok ? 'ALL SPRITES VALID' : 'ERRORS FOUND');
if (process.argv[2]) {   // preview one
  for (const r of NEW[process.argv[2]]) console.log(r.replace(/\./g, ' '));
}
