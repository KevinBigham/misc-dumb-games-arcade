import { chromium } from "playwright";
import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { existsSync, mkdirSync } from "node:fs";
import { extname, join, resolve, sep } from "node:path";
const root = resolve(new URL("../dist/", import.meta.url).pathname);
const shots = new URL("../verification-full/", import.meta.url).pathname;
mkdirSync(shots, { recursive: true });
const mime = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".png": "image/png" };
const server = createServer(async (req, res) => {
  try {
    const pathname = decodeURIComponent(req.url.split("?")[0]);
    const raw = pathname === "/" ? "/index.html" : pathname;
    const file = resolve(root, "." + raw);
    if (file !== root && !file.startsWith(root + sep)) { res.writeHead(403).end(); return; }
    const data = await readFile(file);
    res.writeHead(200, { "content-type": mime[extname(file)] || "application/octet-stream" });
    res.end(data);
  } catch { res.writeHead(404).end(); }
});
await new Promise((resolve) => server.listen(0, resolve));
const port = server.address().port;
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", args: ["--no-sandbox", "--disable-gpu-sandbox"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
page.on("pageerror", (error) => errors.push(String(error)));
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const snap = () => page.evaluate(() => window.__souperDebug.snapshot());
const shot = (name) => page.screenshot({ path: join(shots, name) });
try {
  await page.goto(`http://127.0.0.1:${port}/?debug&seed=42`, { waitUntil: "networkidle" });
  await page.waitForFunction(() => window.__GAME_READY__ === true);
  await page.evaluate(() => { localStorage.clear(); });
  await page.reload({ waitUntil: "networkidle" });
  await page.waitForFunction(() => window.__GAME_READY__ === true);
  await shot("01-title.png");
  await page.click('[data-action="help"]');
  assert(await page.locator("#help-screen").isVisible(), "Help did not open");
  await page.click('#help-screen [data-action="close-help"]');
  assert(await page.locator("#title-screen").isVisible(), "Help did not return to title");
  await page.keyboard.press("Space");
  await page.waitForTimeout(500);
  assert((await snap()).mode === "playing", "Space did not start play");
  await page.mouse.move(850, 320);
  await page.mouse.down();
  await page.waitForTimeout(550);
  await page.mouse.up();
  assert((await snap()).playerShots > 0, "Mouse fire produced no soup projectiles");
  await page.keyboard.press("Escape");
  await page.waitForTimeout(200);
  assert((await snap()).mode === "paused", "Escape did not pause");
  await shot("02-pause.png");
  await page.click('[data-action="quality"]');
  assert((await snap()).quality === "low", "Quality button did not switch to low");
  await page.click('#pause-mute-button');
  assert((await page.locator('#pause-mute-button').textContent()).includes("OFF"), "Mute button did not mute");
  await page.click('#pause-mute-button');
  await page.click('[data-action="resume"]');
  assert((await snap()).mode === "playing", "Resume did not resume");
  await page.evaluate(() => window.__souperDebug.upgrade());
  await page.waitForTimeout(150);
  assert(await page.locator(".upgrade-card").count() === 3, "Upgrade draft does not have three cards");
  await shot("03-upgrades.png");
  await page.locator(".upgrade-card").nth(1).click();
  assert((await snap()).wave === 2 && Object.keys((await snap()).upgrades).length === 1, "Upgrade selection did not advance the run");
  await page.evaluate(() => window.__souperDebug.vending());
  await page.keyboard.press("KeyE");
  await page.waitForTimeout(200);
  assert((await snap()).coupons === 38 && Object.values((await snap()).upgrades).reduce((sum, level) => sum + level, 0) === 2, "Vending did not trade coupons for a mutation");
  await page.evaluate(() => {
    window.__souperDebug.start();
    window.__souperDebug.secret();
  });
  await page.waitForTimeout(1500);
  assert((await snap()).banana && (await snap()).save.banana, "Golden banana did not unlock and persist");
  await page.evaluate(() => window.__souperDebug.scream());
  await page.keyboard.press("KeyQ");
  await page.waitForTimeout(150);
  await page.evaluate(() => window.__souperDebug.boss("fridge"));
  await page.waitForTimeout(4300);
  assert((await snap()).wave === 3 && (await snap()).enemyShots > 0, "Fridge boss did not use projectile attacks");
  await shot("04-fridge.png");
  await page.evaluate(() => { window.__souperDebug.quality("high"); window.__souperDebug.busy(); });
  await page.waitForTimeout(4500);
  const busy = await snap();
  assert(busy.enemies >= 25, "Busy scene did not spawn the enemy budget");
  await shot("05-busy.png");
  await page.evaluate(() => window.__souperDebug.boss("manager"));
  await page.waitForTimeout(5200);
  assert((await snap()).wave === 7 && (await snap()).enemyShots > 0, "Manager boss did not attack");
  await shot("06-manager.png");
  await page.evaluate(() => window.__souperDebug.lose());
  assert((await snap()).mode === "gameover", "Fatal damage did not reach game over");
  await shot("07-gameover.png");
  await page.click('#end-screen [data-action="restart"]');
  const restarted = await snap();
  assert(restarted.mode === "playing" && restarted.wave === 1 && restarted.score === 0 && restarted.hp === 100, "Restart retained old run residue");
  await page.evaluate(() => window.__souperDebug.win());
  assert((await snap()).mode === "victory" && (await snap()).save.nightmareUnlocked, "Victory did not unlock Nightmare Shift");
  await shot("08-victory.png");
  await page.click('#end-screen [data-action="title"]');
  await page.click('[data-action="nightmare"]');
  assert((await page.locator('#nightmare-button').textContent()).includes("ON"), "Nightmare toggle did not respond");
  await page.reload({ waitUntil: "networkidle" });
  await page.waitForFunction(() => window.__GAME_READY__ === true);
  assert((await snap()).save.banana && (await snap()).save.wins >= 1, "Save data did not survive reload");
  await page.setViewportSize({ width: 800, height: 600 });
  await page.waitForTimeout(200);
  await shot("09-small-window.png");
  const gpu = await page.evaluate(() => {
    const gl = document.getElementById("game-canvas").getContext("webgl2");
    const ext = gl.getExtension("WEBGL_debug_renderer_info");
    return ext ? gl.getParameter(ext.UNMASKED_RENDERER_WEBGL) : gl.getParameter(gl.RENDERER);
  });
  assert(errors.length === 0, `Console errors: ${errors.join(" | ")}`);
  console.log(JSON.stringify({ result: "FULL VERIFY OK", busy, gpu, screenshots: shots }, null, 2));
} finally {
  await browser.close();
  server.close();
}
